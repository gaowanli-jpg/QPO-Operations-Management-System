import { describe, expect, test } from 'vitest'
import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const currentDir = dirname(fileURLToPath(import.meta.url))
const readSource = (...segments) => readFileSync(resolve(currentDir, ...segments), 'utf8')

const dictApi = readSource('services', 'dictApi.js')
const dictionaryStore = readSource('stores', 'dictionaryStore.js')
const materialProcess = readSource('components', 'MaterialProcessManage.vue')

describe('process master management frontend workflow', () => {
  test('dictApi exposes two-level process master APIs', () => {
    expect(dictApi).toContain('listProcessCategories')
    expect(dictApi).toContain('/api/dict/process-categories')
    expect(dictApi).toContain('pageProcessCategories')
    expect(dictApi).toContain('/api/dict/process-categories/page')
    expect(dictApi).toContain('saveProcessCategory')
    expect(dictApi).toContain('listProcessDetails')
    expect(dictApi).toContain('/api/dict/process-details')
    expect(dictApi).toContain('pageProcessDetails')
    expect(dictApi).toContain('/api/dict/process-details/page')
    expect(dictApi).toContain('saveProcessDetail')
    expect(dictApi).toContain('deleteProcessDetail')
    expect(dictApi).toContain("method: 'DELETE'")
  })

  test('dictionary store caches process categories and detail options', () => {
    expect(dictionaryStore).toContain('processCategories: []')
    expect(dictionaryStore).toContain('processDetails: []')
    expect(dictionaryStore).toContain('listProcessCategories')
    expect(dictionaryStore).toContain('listProcessDetails')
    expect(dictionaryStore).toContain('processDetailId')
    expect(dictionaryStore).toContain('processCode')
    expect(dictionaryStore).toContain('categoryName')
    expect(dictionaryStore).toContain('detailName')
    expect(dictionaryStore).toContain('hourlyRate')
    expect(dictionaryStore).toContain('detailHourlyRate')
    expect(dictionaryStore).toContain('categoryHourlyRate')
    expect(dictionaryStore).toContain('effectiveHourlyRate')
    expect(dictionaryStore).toContain('detailEnabled')
    expect(dictionaryStore).toContain('categoryEnabled')
    expect(dictionaryStore).toContain('effectiveEnabled')
    expect(dictionaryStore).toContain('processName: item.detailName')
    expect(dictionaryStore).toContain("calcType: '工时'")
  })

  test('material process page supports custom detail create/delete while keeping process category read-only', () => {
    expect(materialProcess).toContain('工艺大类')
    expect(materialProcess).toContain('具体工艺')
    expect(materialProcess).toContain('processCategoryKeyword')
    expect(materialProcess).toContain('processDetailKeyword')
    expect(materialProcess).toContain('loadProcessCategoryPage')
    expect(materialProcess).toContain('loadProcessDetailPage')
    expect(materialProcess).toContain(':data="processCategories"')
    expect(materialProcess).toContain(':data="processDetails"')
    expect(materialProcess).toContain('pageProcessCategories({')
    expect(materialProcess).toContain('pageProcessDetails({')
    expect(materialProcess).toContain('processCategoryPagination')
    expect(materialProcess).toContain('processDetailPagination')
    expect(materialProcess).toContain('processCategoryPagination.total')
    expect(materialProcess).toContain('processDetailPagination.total')
    expect(materialProcess).toContain('resetProcessCategoryPage')
    expect(materialProcess).toContain('resetProcessDetailPage')
    expect(materialProcess).not.toContain('paginateRows(filteredProcessCategories')
    expect(materialProcess).not.toContain('paginateRows(filteredProcessDetails')
    expect(materialProcess).toContain('工艺编码')
    expect(materialProcess).toContain('工艺名称')
    expect(materialProcess).toContain('小时价格')
    expect(materialProcess).toContain('具体小时价格')
    expect(materialProcess).toContain('大类小时价格')
    expect(materialProcess).toContain('核价使用价格')
    expect(materialProcess).toContain('detailHourlyRate')
    expect(materialProcess).toContain('categoryHourlyRate')
    expect(materialProcess).toContain('effectiveHourlyRate')
    expect(materialProcess).toContain('detailEnabled')
    expect(materialProcess).toContain('categoryEnabled')
    expect(materialProcess).toContain('effectiveEnabled')
    expect(materialProcess).toContain('来源')
    expect(materialProcess).toContain('状态')
    expect(materialProcess).toContain('备注')
    expect(materialProcess).toContain('具体备注')
    expect(materialProcess).not.toContain('@click="openProcessCategoryDialog')
    expect(materialProcess).toContain('@click="openProcessDetailDialog()"')
    expect(materialProcess).toContain('@click="openProcessDetailDialog(scope.row)"')
    expect(materialProcess).toContain(':disabled="!!processDetailForm.id"')
    expect(materialProcess).toContain(':readonly="!!processDetailForm.id"')
    expect(materialProcess).toContain('saveProcessDetail')
    expect(materialProcess).toContain('deleteProcessDetail')
    expect(materialProcess).toContain('isProcessDetailDeletePending(scope.row)')
    expect(materialProcess).toContain("v-permission=\"'engineer:dict:process-manage'\"")
  })

  test('process page keeps other dictionary tabs and removes tier price editing from process master', () => {
    expect(materialProcess).toContain('name="materials"')
    expect(materialProcess).toContain('name="pricingMarkupFees"')
    expect(materialProcess).toContain('基础百分比费用')
    expect(materialProcess).toContain('税率')
    expect(materialProcess).toContain('客户权重')
    expect(materialProcess).toContain('pricingScope')
    expect(materialProcess).toContain('feeCategory')
    expect(materialProcess).toContain('systemRequired')
    expect(materialProcess).toContain('name="extraFees"')
    expect(materialProcess).not.toContain('processPriceFields')
    expect(materialProcess).not.toContain('price1To5')
    expect(materialProcess).not.toContain('price3000Plus')
  })

  test('process master layout has responsive safeguards', () => {
    expect(materialProcess).toContain('process-master-grid')
    expect(materialProcess).toContain('process-dialog-grid')
    expect(materialProcess).toContain('@media (max-width: 900px)')
  })
})
