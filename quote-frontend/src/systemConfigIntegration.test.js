import { describe, expect, test } from 'vitest'
import { existsSync, readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const currentDir = dirname(fileURLToPath(import.meta.url))
const readSource = (...segments) => readFileSync(resolve(currentDir, ...segments), 'utf8')
const readOptionalSource = (...segments) => {
  const file = resolve(currentDir, ...segments)
  return existsSync(file) ? readFileSync(file, 'utf8') : ''
}

const systemConfigApi = readSource('services', 'systemConfigApi.js')
const systemConfigManage = readSource('components', 'SystemConfigManage.vue')
const integrationPanel = readOptionalSource('components', 'system-config', 'SystemIntegrationConfigPanel.vue')
const inboundPanel = readOptionalSource('components', 'system-config', 'SystemInboundCallbackConfigPanel.vue')

describe('QPO system integration config frontend', () => {
  test('defines system integration config API service contract', () => {
    expect(systemConfigApi).toContain("export const listIntegrationConfigs = (params = {}) => request('/api/system/integration-configs', { params })")
    expect(systemConfigApi).toContain("export const getActiveIntegrationConfigs = () => request('/api/system/integration-configs/active')")
    expect(systemConfigApi).toContain('export const saveIntegrationConfig = (payload) =>')
    expect(systemConfigApi).toContain("request(id ? `/api/system/integration-configs/${id}` : '/api/system/integration-configs'")
    expect(systemConfigApi).toContain('export const testIntegrationConfig = (id) => request(`/api/system/integration-configs/${id}/test`, {')
    expect(systemConfigApi).toContain('export const activateIntegrationConfig = (id) => request(`/api/system/integration-configs/${id}/activate`, {')
    expect(systemConfigApi).toContain('export const disableIntegrationConfig = (id) => request(`/api/system/integration-configs/${id}/disable`, {')
    expect(systemConfigApi).toContain("export const listDataCenterConfigs = () => request('/api/system/data-center-configs')")
    expect(systemConfigApi).toContain('export const saveDataCenterConfig = (payload) =>')
    expect(systemConfigApi).toContain("request(id ? `/api/system/data-center-configs/${id}` : '/api/system/data-center-configs'")
    expect(systemConfigApi).toContain('export const testDataCenterToken = (id) => request(`/api/system/data-center-configs/${id}/test-token`, {')
    expect(systemConfigApi).toContain('export const activateDataCenterConfig = (id) => request(`/api/system/data-center-configs/${id}/activate`, {')
    expect(systemConfigApi).toContain('export const disableDataCenterConfig = (id) => request(`/api/system/data-center-configs/${id}/disable`, {')
    expect(systemConfigApi).toContain("export const listDataCenterEndpoints = () => request('/api/system/data-center-endpoints')")
    expect(systemConfigApi).toContain('export const saveDataCenterEndpoint = (endpointCode, payload) => request(`/api/system/data-center-endpoints/${endpointCode}`, {')
    expect(systemConfigApi).toContain('export const testDataCenterEndpoint = (endpointCode) => request(`/api/system/data-center-endpoints/${endpointCode}/test`, {')
  })

  test('splits system config page into storage outbound and inbound tabs', () => {
    expect(systemConfigManage).toContain('el-tabs')
    expect(systemConfigManage).toContain('name="storage"')
    expect(systemConfigManage).toContain('name="outbound"')
    expect(systemConfigManage).toContain('name="inbound"')
    expect(systemConfigManage).toContain('<SystemStorageConfigPanel />')
    expect(systemConfigManage).toContain('<SystemIntegrationConfigPanel />')
    expect(systemConfigManage).toContain('<SystemInboundCallbackConfigPanel />')
    expect(systemConfigManage).toContain('文件存储')
    expect(systemConfigManage).toContain('出站接口')
    expect(systemConfigManage).toContain('入站接口')
    expect(systemConfigManage).not.toContain('name="integration"')
  })

  test('renders data center connection and endpoint workbench as the primary outbound layout', () => {
    expect(integrationPanel).toContain('system-integration-config-panel')
    expect(integrationPanel).toContain('出站接口')
    expect(integrationPanel).toContain('统一配置数据中心连接，并按业务功能维护 MES / WMS / U9 的数据中心接口 path。')
    expect(integrationPanel).toContain('数据中心连接配置')
    expect(integrationPanel).toContain('新增数据中心配置')
    expect(integrationPanel).toContain('编辑数据中心连接')
    expect(integrationPanel).toContain('测试 token')
    expect(integrationPanel).toContain('激活连接')
    expect(integrationPanel).toContain('功能接口配置')
    expect(integrationPanel).toContain('编辑功能接口')
    expect(integrationPanel).toContain('测试接口')
    expect(integrationPanel).toContain('MES_MATERIAL_RESOLVE')
    expect(integrationPanel).toContain('WMS_INVENTORY_ALLOCATE')
    expect(integrationPanel).toContain('U9_SALES_ORDER_SYNC')
    expect(integrationPanel).toContain('MES_PRODUCTION_DISPATCH')
    expect(integrationPanel).toContain('path')
    expect(integrationPanel).toContain('timeoutMs')
    expect(integrationPanel).toContain('enabled')
    expect(integrationPanel).toContain('remark')
    expect(integrationPanel).toContain('targetSystemCode')
    expect(integrationPanel).toContain('requestAdapter')
    expect(integrationPanel).toContain('responseAdapter')
    expect(integrationPanel).toContain('直连 fallback 兼容区')
    expect(integrationPanel).not.toContain('新增直连 U9 fallback')
    expect(integrationPanel).not.toContain('新增直连 MES fallback')
    expect(integrationPanel).not.toContain('新增直连 WMS fallback')
    expect(integrationPanel).not.toContain('authLoginPath')
    expect(integrationPanel).not.toContain('salesOrderCreatePath')
    expect(integrationPanel).not.toContain('materialPath')
    expect(integrationPanel).not.toContain('allocationPath')
    expect(integrationPanel).toContain('clientSecret')
    expect(integrationPanel).toContain('show-password')
    expect(integrationPanel).toContain('******')
    expect(integrationPanel).not.toContain('当前版本未接入')
    expect(integrationPanel).not.toContain('MES 回调 token')
  })

  test('renders inbound callback panel for MES material callback', () => {
    expect(inboundPanel).toContain('system-inbound-callback-config-panel')
    expect(inboundPanel).toContain('入站接口')
    expect(inboundPanel).toContain('MES 物料号回调')
    expect(inboundPanel).toContain('/api/integrations/mes/material-callback')
    expect(inboundPanel).toContain('callbackUrl')
    expect(inboundPanel).toContain('configSource')
    expect(inboundPanel).toContain('tokenConfigured')
    expect(inboundPanel).toContain('保存配置')
    expect(inboundPanel).toContain('生成 token')
    expect(inboundPanel).toContain('复制回调地址')
    expect(inboundPanel).not.toContain('后续阶段接入')
  })

  test('protects integration writes with permissions and duplicate-click guards', () => {
    expect(integrationPanel).toContain("v-permission=\"'system:config:integration:update'\"")
    expect(integrationPanel).toContain("v-permission=\"'system:config:integration:test'\"")
    expect(integrationPanel).toContain("v-permission=\"'system:config:integration:activate'\"")
    expect(integrationPanel).toContain("dataCenterActionKeys.saveDialog")
    expect(integrationPanel).toContain("dataCenterActionKeys.endpointSaveDialog")
    expect(integrationPanel).toContain("testToken: (configId) => `system:config:data-center:test-token:${configId || 'none'}`")
    expect(integrationPanel).toContain("activate: (configId) => `system:config:data-center:activate:${configId || 'none'}`")
    expect(integrationPanel).toContain("endpointTest: (endpointCode) => `system:config:data-center-endpoint:test:${endpointCode || 'none'}`")
    expect(integrationPanel).toContain(':loading="isPending(dataCenterActionKeys.saveDialog)"')
    expect(integrationPanel).toContain(':loading="isPending(dataCenterActionKeys.endpointSaveDialog)"')
    expect(integrationPanel).toContain(':loading="isPending(dataCenterActionKeys.testToken(row.id))"')
    expect(integrationPanel).toContain(':loading="isPending(dataCenterActionKeys.endpointTest(row.endpointCode))"')
    expect(integrationPanel).toContain(':disabled="isDataCenterRowPending(row)"')
    expect(integrationPanel).toContain(':disabled="isEndpointRowPending(row)"')
    expect(integrationPanel).toContain('runAction(dataCenterActionKeys.saveDialog')
    expect(integrationPanel).toContain('runAction(dataCenterActionKeys.endpointSaveDialog')
    expect(integrationPanel).toContain('runAction(dataCenterActionKeys.testToken(row.id)')
    expect(integrationPanel).toContain('runAction(dataCenterActionKeys.endpointTest(row.endpointCode)')
  })
})
