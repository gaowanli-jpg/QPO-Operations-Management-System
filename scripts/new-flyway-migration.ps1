param(
    [Parameter(Mandatory = $true)]
    [string]$Name,
    [string]$ProjectRoot = "",
    [string]$ContainerName = "quote-postgres",
    [switch]$DryRun
)

$ErrorActionPreference = "Stop"
$FIRST_POST_BASELINE_VERSION = 5

if ([string]::IsNullOrWhiteSpace($ProjectRoot)) {
    $ProjectRoot = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
}

function Get-MigrationVersions($MigrationDir) {
    if (-not (Test-Path $MigrationDir)) { return @() }
    Get-ChildItem -Path $MigrationDir -Filter "V*.sql" -File | ForEach-Object {
        if ($_.Name -match '^V(\d+)__.+\.sql$') { [int]$Matches[1] }
    }
}

function Get-ContainerState($Name) {
    $state = (& docker inspect -f '{{.State.Status}}' $Name 2>$null)
    if ($LASTEXITCODE -ne 0) { return $null }
    return ($state | Select-Object -First 1).Trim()
}

function Get-PostgresEnv($Name, $Key, $Fallback) {
    $value = (& docker exec $Name printenv $Key 2>$null)
    if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($value)) { return $Fallback }
    return ($value | Select-Object -First 1).Trim()
}

function Get-DatabaseMaxFlywayVersion($Name) {
    $state = Get-ContainerState $Name
    if ($state -ne "running") { return 0 }

    $dbUser = Get-PostgresEnv $Name "POSTGRES_USER" "postgres"
    $dbName = Get-PostgresEnv $Name "POSTGRES_DB" "postgres"
    $query = "SELECT COALESCE(MAX(version::int), 0) FROM flyway_schema_history WHERE success AND version ~ '^[0-9]+$';"
    $value = (& docker exec $Name psql -U $dbUser -d $dbName -At -c $query 2>$null)
    if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($value)) { return 0 }
    return [int](($value | Select-Object -First 1).Trim())
}

function ConvertTo-Slug($Value) {
    $slug = $Value.ToLowerInvariant() -replace '[^a-z0-9]+', '_'
    $slug = $slug.Trim('_') -replace '_+', '_'
    if ([string]::IsNullOrWhiteSpace($slug)) {
        throw "Migration name must contain at least one ASCII letter or number, for example: u9_customer_sync_schedule_config"
    }
    return $slug
}

$migrationDir = Join-Path $ProjectRoot "quote-backend/src/main/resources/db/migration"
if (-not (Test-Path $migrationDir)) {
    throw "Flyway migration directory not found: $migrationDir"
}

$repoVersions = @(Get-MigrationVersions $migrationDir)
$repoMax = if ($repoVersions.Count -gt 0) { ($repoVersions | Measure-Object -Maximum).Maximum } else { 0 }
$dbMax = Get-DatabaseMaxFlywayVersion $ContainerName
$floor = $FIRST_POST_BASELINE_VERSION - 1
$nextVersion = (($repoMax, $dbMax, $floor) | Measure-Object -Maximum).Maximum + 1
$slug = ConvertTo-Slug $Name
$fileName = "V$nextVersion`__$slug.sql"
$target = Join-Path $migrationDir $fileName

if (Test-Path $target) {
    throw "Migration already exists: $target"
}

Write-Host "Next Flyway migration: $fileName (repoMax=V$repoMax dbMax=V$dbMax firstPostBaseline=V$FIRST_POST_BASELINE_VERSION)"

if ($DryRun) {
    return
}

$content = @"
-- TODO: describe the schema change.
-- Generated by scripts/new-flyway-migration.ps1. Keep this migration idempotent when possible.

SET search_path TO `"`${flyway:defaultSchema}`";

-- Add migration SQL here.
"@

New-Item -Path $target -ItemType File -Value $content -Encoding UTF8 | Out-Null
Write-Host "Created $target"
