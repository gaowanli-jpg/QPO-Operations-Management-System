package com.machining.quote;

import com.machining.quote.dto.PartVersionKey;
import com.machining.quote.mapper.RepeatQuoteSourceSqlProvider;
import org.junit.jupiter.api.Test;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

class SalesOrderQpoImportCharacterizationTest {
    private static final Path MAIN_JAVA = Path.of("src", "main", "java", "com", "machining", "quote");

    @Test
    void importServiceChainsCurrentAutoMatchBeforeAutoDeliveryAndDoesNotUseLegacyEnrichment() throws Exception {
        String importService = Files.readString(
                MAIN_JAVA.resolve(Path.of("service", "SalesOrderQpoImportService.java")),
                StandardCharsets.UTF_8);

        int matchStep = importService.indexOf("autoCompleteProductionSnapshot(header, record, group.getLines().size())");
        int deliveryStep = importService.indexOf("autoGenerateDeliveryTickets(header)");
        assertThat(matchStep).isGreaterThan(0);
        assertThat(deliveryStep).isGreaterThan(matchStep);
        assertThat(importService)
                .contains("autoSnapshotCompletionService.completeImportedOrder(header.getId())")
                .contains("deliveryService.generateImportedSalesOrderTickets(header.getId())")
                .doesNotContain("SalesOrderRepeatEnrichmentService")
                .doesNotContain("SalesOrderRepeatEnrichmentResult")
                .doesNotContain("repeatEnrichmentService");
    }

    @Test
    void legacyRepeatEnrichmentArtifactsAreRemovedAfterAutoSnapshotCompletionCutover() {
        assertThat(Files.exists(MAIN_JAVA.resolve(Path.of("service", "SalesOrderRepeatEnrichmentService.java"))))
                .as("legacy repeat enrichment service should be removed")
                .isFalse();
        assertThat(Files.exists(MAIN_JAVA.resolve(Path.of("dto", "SalesOrderRepeatEnrichmentResult.java"))))
                .as("legacy repeat enrichment result DTO should be removed")
                .isFalse();
    }

    @Test
    void repeatSourceSqlUsesOnlyReleasedRfqItemQuoteVersionsAndAllowsSalesOrderLookupWithoutCurrentRfq() {
        RepeatQuoteSourceSqlProvider provider = new RepeatQuoteSourceSqlProvider();

        Map<String, Object> salesOrderLookupParams = new HashMap<>();
        salesOrderLookupParams.put("currentRfqId", null);
        salesOrderLookupParams.put("keys", List.of(new PartVersionKey("P-001", "A")));
        String salesOrderLookupSql = provider.selectLatestReleasedRepeatSources(salesOrderLookupParams);
        assertThat(salesOrderLookupSql)
                .contains("FROM item_quote_version h")
                .contains("h.status = '\u5df2\u63d0\u5355'")
                .contains("ORDER BY h.id DESC")
                .contains("LIMIT 1")
                .doesNotContain("sales_order_item")
                .doesNotContain("h.rfq_id <> #{currentRfqId}");

        String rfqLookupSql = provider.selectLatestReleasedRepeatSources(Map.of(
                "currentRfqId", 100,
                "keys", List.of(new PartVersionKey("P-001", "A"))
        ));
        assertThat(rfqLookupSql).contains("h.rfq_id <> #{currentRfqId}");
    }
}
